fun wifiCurrent(state: com.example.orb.SetupState): String =
    if (state.wifiStatusKnown) state.currentNetwork.ifBlank { "–" } else tr("Status unbekannt · erneut laden")

fun wifiSaved(state: com.example.orb.SetupState): String =
    if (!state.savedNetworksKnown) trTemplate("savedNetworks", tr("Status unbekannt · erneut laden"))
    else tr(com.example.orb.WifiPresentation.saved(state))

fun quickTitle(quick: com.example.orb.QuickState): String = when (quick.stage) {
    com.example.orb.QuickStage.IDLE -> quick.target?.let { trTemplate("connect", it) } ?: tr("Ein-Klick-Verbindung")
    com.example.orb.QuickStage.ASK_PASSWORD -> trTemplate("passwordFor", quick.target ?: tr("Netzwerk"))
    com.example.orb.QuickStage.CONNECTED -> trTemplate("connectedTo", quick.target ?: tr("Netzwerk"))
    else -> tr(com.example.orb.WifiPresentation.quickTitle(quick))
}

fun wifiOnboarding(state: com.example.orb.SetupState): String = when {
    !state.wifiStatusKnown || !state.savedNetworksKnown -> tr("Status unbekannt · erneut laden")
    state.currentNetwork.isBlank() && state.savedNetworks.isEmpty() -> tr("Noch kein Netzwerk gespeichert.")
    else -> trTemplate("currentNetwork", state.currentNetwork.ifBlank { "–" }, tr(com.example.orb.WifiPresentation.connection(state)))
}

fun wifiSummary(state: com.example.orb.SetupState): String = when {
    !state.wifiStatusKnown || !state.savedNetworksKnown -> tr("Status unbekannt · erneut laden")
    state.currentNetwork.isBlank() && state.savedNetworks.isEmpty() -> tr("nicht eingerichtet")
    state.currentNetwork.isBlank() -> tr("nicht verbunden")
    else -> trTemplate("networkSummary", state.currentNetwork, tr(com.example.orb.WifiPresentation.connection(state)))
}
