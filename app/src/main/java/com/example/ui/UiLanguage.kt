object UiLanguage { var current by mutableStateOf("de") }

/** UI-only translation. Protocol identifiers and agent content never pass through here. */
fun tr(text: String): String = translateUi(text, UiLanguage.current)

fun translateUi(text: String, language: String): String =
    if (language == "en") english[text] ?: text else text

/** Translate only a fixed app-owned template, never inspect or rewrite its arguments. */
fun trTemplate(key: String, vararg args: Any?): String = translateTemplate(key, UiLanguage.current, *args)

fun translateTemplate(key: String, language: String, vararg args: Any?): String {
    val (de, en) = templates[key] ?: error("Unknown UI template: $key")
    require(args.size == Regex("%s").findAll(de).count())
    val pattern = if (language == "en") en else de
    return pattern.split("%s").mapIndexed { index, part ->
        if (index == 0) part else args[index - 1].toString() + part
    }.joinToString("")
}

